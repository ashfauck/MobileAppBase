#!/usr/bin/env node
/**
 * Propagates app.identity.json into the native projects.
 *
 * iOS  -> generates ios/Config/*.xcconfig (bundle id + display name per env)
 * Android -> generates android/app/identity.gradle (consumed by build.gradle)
 * JS   -> generates src/config/identity.generated.ts (typed, importable)
 *
 * Runs automatically on `npm install` (postinstall) and via `npm run identity`.
 * Safe to run before the native folders exist (it just skips them).
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const identityPath = path.join(ROOT, 'app.identity.json');

if (!fs.existsSync(identityPath)) {
  console.warn('[identity] app.identity.json not found — skipping.');
  process.exit(0);
}

/** @type {{appId:string, projectName:string, environments:Record<string,any>}} */
const identity = JSON.parse(fs.readFileSync(identityPath, 'utf8'));
const { appId, projectName, environments } = identity;

if (!appId || !projectName) {
  console.error('[identity] app.identity.json must define "appId" and "projectName".');
  process.exit(1);
}

const ENV_KEYS = Object.keys(environments);
const banner = (comment) =>
  `${comment} AUTO-GENERATED by scripts/apply-app-identity.js — DO NOT EDIT.\n` +
  `${comment} Edit app.identity.json instead, then run: npm run identity\n`;

const writeIfChanged = (filePath, contents) => {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const prev = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (prev === contents) return false;
  fs.writeFileSync(filePath, contents);
  return true;
};

const changed = [];

/* ---------------------------------------------------------------- iOS ---- */
// One xcconfig per environment. The Xcode build configurations point at these,
// and each one #includes the CocoaPods xcconfig for the same configuration.
const iosDir = path.join(ROOT, 'ios');
if (fs.existsSync(iosDir)) {
  for (const key of ENV_KEYS) {
    const env = environments[key];
    const bundleId = `${appId}${env.appIdSuffix || ''}`;

    for (const build of ['Debug', 'Release']) {
      // e.g. Debug-Dev / Release-Prod — matches the Xcode configuration names.
      const configName = `${build}-${key.charAt(0).toUpperCase()}${key.slice(1)}`;
      const podsXcconfig =
        `Pods/Target Support Files/Pods-${projectName}/` +
        `Pods-${projectName}.${configName.toLowerCase()}.xcconfig`;

      const contents =
        banner('//') +
        `#include? "${podsXcconfig}"\n\n` +
        `APP_BUNDLE_ID = ${bundleId}\n` +
        `APP_DISPLAY_NAME = ${env.displayName}\n` +
        `APP_ENVIRONMENT = ${key}\n` +
        `ENVFILE = .env.${key}\n`;

      if (writeIfChanged(path.join(iosDir, 'Config', `${configName}.xcconfig`), contents)) {
        changed.push(`ios/Config/${configName}.xcconfig`);
      }
    }
  }
}

/* ------------------------------------------------------------ Android ---- */
const androidAppDir = path.join(ROOT, 'android', 'app');
if (fs.existsSync(androidAppDir)) {
  const flavorBlocks = ENV_KEYS.map((key) => {
    const env = environments[key];
    const suffix = env.appIdSuffix || '';
    return [
      `        ${env.androidFlavor} {`,
      `            dimension "env"`,
      suffix ? `            applicationIdSuffix "${suffix}"` : `            // production keeps the base applicationId`,
      suffix ? `            versionNameSuffix "-${key}"` : '',
      `            resValue "string", "app_name", "${env.displayName}"`,
      `            buildConfigField "String", "APP_ENVIRONMENT", "\\"${key}\\""`,
      `        }`,
    ]
      .filter(Boolean)
      .join('\n');
  }).join('\n');

  const contents =
    banner('//') +
    `\n` +
    `ext.APP_ID = "${appId}"\n` +
    `ext.PROJECT_NAME = "${projectName}"\n\n` +
    `android {\n` +
    `    defaultConfig {\n` +
    `        applicationId "${appId}"\n` +
    `    }\n\n` +
    `    flavorDimensions += "env"\n\n` +
    `    productFlavors {\n` +
    `${flavorBlocks}\n` +
    `    }\n` +
    `}\n`;

  if (writeIfChanged(path.join(androidAppDir, 'identity.gradle'), contents)) {
    changed.push('android/app/identity.gradle');
  }
}

/* ----------------------------------------------------------------- JS ---- */
const tsEnvUnion = ENV_KEYS.map((k) => `'${k}'`).join(' | ');
const tsEntries = ENV_KEYS.map((key) => {
  const env = environments[key];
  return (
    `  ${key}: {\n` +
    `    appId: '${appId}${env.appIdSuffix || ''}',\n` +
    `    displayName: '${env.displayName}',\n` +
    `  },`
  );
}).join('\n');

const tsContents =
  banner('//') +
  `\n` +
  `export type AppEnvironment = ${tsEnvUnion};\n\n` +
  `export const BASE_APP_ID = '${appId}' as const;\n` +
  `export const PROJECT_NAME = '${projectName}' as const;\n\n` +
  `export const APP_IDENTITY: Record<\n` +
  `  AppEnvironment,\n` +
  `  { appId: string; displayName: string }\n` +
  `> = {\n${tsEntries}\n};\n`;

if (writeIfChanged(path.join(ROOT, 'src', 'config', 'identity.generated.ts'), tsContents)) {
  changed.push('src/config/identity.generated.ts');
}

/* ------------------------------------------------------------- report ---- */
if (changed.length) {
  console.log(`[identity] ${appId} / ${projectName} — updated:`);
  changed.forEach((f) => console.log(`[identity]   ${f}`));
} else {
  console.log(`[identity] ${appId} / ${projectName} — already up to date.`);
}
